function tokenize(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/[^a-z0-9\s']/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 1);
}

const records = [];
let n = 0;

function add(kind, q, a, extraTags) {
  n += 1;
  const tags = Array.from(new Set(tokenize(q).concat(tokenize(kind)).concat(extraTags || [])));
  records.push(rec("kb_" + n, kind, q, a, tags));
}

